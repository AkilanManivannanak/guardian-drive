"""Compare real-only and DDPM-augmented WESAD classifiers on unseen people.

The generated windows must have been sampled from a model that did not train on
any evaluation subject. This benchmark is an engineering utility experiment,
not clinical validation or a privacy guarantee.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Dict, List, Sequence, Tuple

import numpy as np
import torch
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import balanced_accuracy_score, f1_score

from generative.wesad_diffusion import (
    CHANNELS,
    CLASS_LABELS,
    DEFAULT_HELDOUT,
    collect_windows,
)


def subject_ids(value: str) -> Tuple[int, ...]:
    return tuple(int(item.strip().lstrip("sS")) for item in value.split(",") if item.strip())


def normalize(windows: np.ndarray, mean: np.ndarray, std: np.ndarray) -> np.ndarray:
    return np.clip((windows - mean) / np.maximum(std, 1e-5), -5, 5).astype(np.float32)


def flatten(windows: np.ndarray) -> np.ndarray:
    # Every window uses the generator's fixed channel order and time alignment.
    return windows.reshape(len(windows), -1)


def bootstrap_difference(
    real_scores: Sequence[float], augmented_scores: Sequence[float], seed: int, reps: int = 5000
) -> Tuple[float, float]:
    differences = np.asarray(augmented_scores) - np.asarray(real_scores)
    if len(differences) < 2:
        return float("nan"), float("nan")
    rng = np.random.default_rng(seed)
    samples = rng.choice(differences, size=(reps, len(differences)), replace=True).mean(axis=1)
    return tuple(float(item) for item in np.quantile(samples, [0.025, 0.975]))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--wesad-root", type=Path, required=True)
    parser.add_argument("--checkpoint", type=Path, required=True)
    parser.add_argument("--synthetic", type=Path, required=True,
                        help="NPZ emitted by wesad_diffusion.py --samples-per-class")
    parser.add_argument("--test-subjects", default=",".join(map(str, DEFAULT_HELDOUT)))
    parser.add_argument("--synthetic-per-class", type=int, default=500)
    parser.add_argument("--output", type=Path, default=Path("outputs/wesad_augmentation_eval.json"))
    args = parser.parse_args()

    # Checkpoint files are generated by this repository and contain a PyTorch
    # pickle. Load only checkpoints from trusted local runs.
    checkpoint = torch.load(args.checkpoint, map_location="cpu", weights_only=False)
    train_subjects = set(checkpoint["train_subjects"])
    test_subjects = subject_ids(args.test_subjects)
    overlap = train_subjects.intersection(test_subjects)
    if overlap:
        parser.error(f"Test subjects overlap generator training subjects: {sorted(overlap)}")

    with np.load(args.synthetic, allow_pickle=False) as archive:
        synthetic = archive["windows"].astype(np.float32)
        synthetic_labels = archive["labels"].astype(np.int64)
        channels = tuple(str(item) for item in archive["channels"].tolist())
        is_normalized = bool(archive["normalized"])
        synthetic_mean = archive["normalization_mean"].astype(np.float32).reshape(1, 1, -1)
        synthetic_std = archive["normalization_std"].astype(np.float32).reshape(1, 1, -1)
    if channels != tuple(CHANNELS):
        parser.error(f"Channel mismatch: expected {CHANNELS}, found {channels}")
    if not is_normalized:
        parser.error("Synthetic windows must include the normalized=true metadata")
    if not np.allclose(synthetic_mean.reshape(-1), checkpoint["mean"].reshape(-1)) or not np.allclose(
        synthetic_std.reshape(-1), checkpoint["std"].reshape(-1)
    ):
        parser.error("Synthetic window normalization does not match the supplied checkpoint")

    generated_indices: List[int] = []
    for label in CLASS_LABELS:
        indices = np.flatnonzero(synthetic_labels == label)[: args.synthetic_per_class]
        if len(indices) < args.synthetic_per_class:
            parser.error(
                f"Need {args.synthetic_per_class} generated windows for label {label}; found {len(indices)}"
            )
        generated_indices.extend(indices.tolist())
    synthetic = np.clip(synthetic[generated_indices], -5, 5)
    synthetic_labels = synthetic_labels[generated_indices]

    train_windows, train_labels = collect_windows(args.wesad_root, sorted(train_subjects))
    train_windows = normalize(train_windows, checkpoint["mean"], checkpoint["std"])
    augmented_x = np.concatenate((train_windows, synthetic), axis=0)
    augmented_y = np.concatenate((train_labels, synthetic_labels), axis=0)
    real_model = LogisticRegression(
        C=0.01, class_weight="balanced", max_iter=1500, random_state=42
    ).fit(flatten(train_windows), train_labels)
    augmented_model = LogisticRegression(
        C=0.01, class_weight="balanced", max_iter=1500, random_state=42
    ).fit(flatten(augmented_x), augmented_y)
    per_subject: List[Dict[str, object]] = []
    real_balanced, augmented_balanced = [], []
    real_f1, augmented_f1 = [], []
    for subject_id in test_subjects:
        test_windows, test_labels = collect_windows(args.wesad_root, [subject_id])
        test_windows = normalize(test_windows, checkpoint["mean"], checkpoint["std"])
        real_prediction = real_model.predict(flatten(test_windows))
        augmented_prediction = augmented_model.predict(flatten(test_windows))
        real_ba = float(balanced_accuracy_score(test_labels, real_prediction))
        real_macro_f1 = float(
            f1_score(test_labels, real_prediction, labels=CLASS_LABELS, average="macro", zero_division=0)
        )
        aug_ba = float(balanced_accuracy_score(test_labels, augmented_prediction))
        aug_macro_f1 = float(
            f1_score(test_labels, augmented_prediction, labels=CLASS_LABELS, average="macro", zero_division=0)
        )
        real_balanced.append(real_ba)
        augmented_balanced.append(aug_ba)
        real_f1.append(real_macro_f1)
        augmented_f1.append(aug_macro_f1)
        per_subject.append(
            {
                "subject": f"S{subject_id}",
                "real_only_balanced_accuracy": real_ba,
                "real_plus_synthetic_balanced_accuracy": aug_ba,
                "real_only_macro_f1": real_macro_f1,
                "real_plus_synthetic_macro_f1": aug_macro_f1,
                "test_windows": len(test_windows),
            }
        )

    result = {
        "protocol": "subject-held-out; same LogisticRegression features and settings",
        "generator_train_subjects": sorted(train_subjects),
        "evaluation_subjects": [f"S{item}" for item in test_subjects],
        "synthetic_windows_per_class": args.synthetic_per_class,
        "class_labels": list(CLASS_LABELS),
        "channels": list(CHANNELS),
        "per_subject": per_subject,
        "mean_subject_balanced_accuracy": {
            "real_only": float(np.mean(real_balanced)),
            "real_plus_synthetic": float(np.mean(augmented_balanced)),
            "difference": float(np.mean(augmented_balanced) - np.mean(real_balanced)),
            "paired_subject_bootstrap_95pct_ci": bootstrap_difference(
                real_balanced, augmented_balanced, 42
            ),
        },
        "mean_subject_macro_f1": {
            "real_only": float(np.mean(real_f1)),
            "real_plus_synthetic": float(np.mean(augmented_f1)),
            "difference": float(np.mean(augmented_f1) - np.mean(real_f1)),
            "paired_subject_bootstrap_95pct_ci": bootstrap_difference(real_f1, augmented_f1, 43),
        },
        "limitations": [
            "Small public dataset; subject-level uncertainty is substantial.",
            "This classifier is a controlled utility probe, not a production drowsiness model.",
            "A positive result does not establish privacy or clinical validity.",
        ],
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(result, indent=2))
    print(f"report={args.output}")


if __name__ == "__main__":
    main()
